#!/usr/bin/env python3
"""Project the kept-experience study's saved records into the website's data file.

The study's files live at a fixed revision (STUDY_REVISION). This script reads
them from git objects, never from the working tree, and writes
site/src/content/keptExperience.json: the rows of results.json unchanged, plus
per-problem scores and one worked example recomputed from the saved score files.
It stops if the recomputed figures disagree with results.json.

    python scripts/build_kept_experience_site_data.py          # write
    python scripts/build_kept_experience_site_data.py --check  # compare, needs the revision fetched
"""
from __future__ import annotations

import argparse
import gzip
import hashlib
import json
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "site" / "src" / "content" / "keptExperience.json"
STUDY_REVISION = "2b325e2de0fb763d0998f2a4f61fac59001ded59"
STUDY_DIR = "docs/studies/kept-experience"
EVIDENCE_DIR = "examples/kept-experience"
EXAMPLE_TASK = "HumanEval/37"


def show(path: str) -> bytes:
    return subprocess.run(
        ["git", "show", f"{STUDY_REVISION}:{path}"], cwd=ROOT, capture_output=True, check=True
    ).stdout


def score_rows(arm: str) -> list[dict]:
    return json.loads(show(f"{EVIDENCE_DIR}/scores/{arm}__heldout__natural.json"))["rows"]


def per_problem(arm: str) -> tuple[dict[str, float], dict[str, int]]:
    shares: dict[str, list[float]] = defaultdict(list)
    faults: dict[str, int] = {}
    for row in score_rows(arm):
        shares[row["task_id"]].append(len(row["killed"]) / row["n_faults"])
        faults[row["task_id"]] = row["n_faults"]
    return {task: sum(v) / len(v) for task, v in shares.items()}, faults


def model_name(sample: str) -> str:
    return {"chatgpt": "ChatGPT", "codegen-16b": "CodeGen-16B", "incoder-6b": "InCoder-6B"}.get(
        sample.split("_temp_")[0], sample
    )


def build() -> dict:
    results_bytes = show(f"{STUDY_DIR}/results.json")
    results = json.loads(results_bytes)
    none, faults = per_problem("cold")
    record, _ = per_problem("kept")

    primary = {row["arm"]: row for row in results["primary"]["rows"]}
    wins = sum(record[t] > none[t] + 1e-12 for t in none)
    losses = sum(record[t] < none[t] - 1e-12 for t in none)
    recomputed = {
        "problems": len(none),
        "none_mean": round(sum(none.values()) / len(none), 4),
        "record_mean": round(sum(record.values()) / len(record), 4),
        "wins": wins,
        "losses": losses,
        "ties": len(none) - wins - losses,
    }
    expected = {
        "problems": primary["kept"]["problems"],
        "none_mean": primary["cold"]["mean"],
        "record_mean": primary["kept"]["mean"],
        "wins": primary["kept"]["wins"],
        "losses": primary["kept"]["losses"],
        "ties": primary["kept"]["ties"],
    }
    if recomputed != expected:
        raise SystemExit(f"score files disagree with results.json: {recomputed} != {expected}")

    population = json.loads(gzip.decompress(show(f"{EVIDENCE_DIR}/faults.json.gz")))
    example_faults = [
        {
            "id": f"{EXAMPLE_TASK}#n{index}",
            "models": sorted({model_name(m) for m in fault["models"]}),
            "source": fault["source"],
        }
        for index, fault in enumerate(population[EXAMPLE_TASK])
        if fault["kind"] == "natural"
    ]
    example_runs = [
        {
            "arm": arm,
            "run": row["rep"] + 1,
            "inputs": [json.dumps(args)[1:-1] for args in row["inputs"]],
            "valid": row["n_valid"],
            "exposed": row["killed"],
        }
        for arm in ("cold", "kept")
        for row in score_rows(arm)
        if row["task_id"] == EXAMPLE_TASK
    ]

    return {
        "about": "Generated by scripts/build_kept_experience_site_data.py from the study revision below. Do not edit.",
        "revision": STUDY_REVISION,
        "results_sha256": hashlib.sha256(results_bytes).hexdigest(),
        "held_out": {
            "problems": len(none),
            "fault_classes": sum(faults.values()),
            "runs": 2,
        },
        "results": results,
        "problems": [
            {"task": task, "faults": faults[task], "none": round(none[task], 4), "record": round(record[task], 4)}
            for task in sorted(none, key=lambda t: int(t.split("/")[1]))
        ],
        "example": {"task": EXAMPLE_TASK, "faults": example_faults, "runs": example_runs},
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the committed file is out of date")
    args = parser.parse_args()
    text = json.dumps(build(), indent=1, ensure_ascii=False) + "\n"
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is out of date; run this script without --check", file=sys.stderr)
            return 1
        print(f"{OUT.relative_to(ROOT)} matches the study revision {STUDY_REVISION[:7]}")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
